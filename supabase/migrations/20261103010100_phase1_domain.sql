-- ─── 4. Value checks (NOT VALID: they apply to new and changed rows, not to old data) ─
create or replace function pg_temp.add_check(p_table text, p_name text, p_expr text)
returns void language plpgsql as $$
begin
  if not exists (select 1 from pg_constraint where conname = p_name) then
    execute format('alter table public.%I add constraint %I check (%s) not valid', p_table, p_name, p_expr);
  end if;
end $$;

