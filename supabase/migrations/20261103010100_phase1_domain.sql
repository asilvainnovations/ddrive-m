insert into public.ddrive_counters (tenant_id, prefix, last_value)
select tenant_id, prefix, max(num)
from (
  select tenant_id, 'R' as prefix, coalesce(nullif(substring(ref from '([0-9]+)$'), '')::int, 0) as num from public.ddrive_risks
  union all select tenant_id, 'I', coalesce(nullif(substring(ref from '([0-9]+)$'), '')::int, 0) from public.ddrive_incidents
  union all select tenant_id, 'P', coalesce(nullif(substring(ref from '([0-9]+)$'), '')::int, 0) from public.ddrive_plans
  union all select tenant_id, 'D', coalesce(nullif(substring(ref from '([0-9]+)$'), '')::int, 0) from public.ddrive_documents
) s
group by tenant_id, prefix
on conflict (tenant_id, prefix) do update set last_value = greatest(public.ddrive_counters.last_value, excluded.last_value);

