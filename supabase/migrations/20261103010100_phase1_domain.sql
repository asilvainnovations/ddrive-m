-- ─── 3. Move existing data into one organisation ─────────────────────────────
do $$
declare
  v_tenant uuid;
  v_needs boolean := false;
  t text;
  n bigint;
begin
  foreach t in array array['ddrive_hazards', 'ddrive_risks', 'ddrive_incidents', 'ddrive_undrr_scores',
                           'ddrive_scenarios', 'ddrive_plans', 'ddrive_messages', 'ddrive_documents'] loop
    execute format('select count(*) from public.%I where tenant_id is null', t) into n;
    if n > 0 then v_needs := true; end if;
  end loop;
  if exists (select 1 from public.ddrive_users u
             where not exists (select 1 from public.ddrive_memberships m where m.user_id = u.id)) then
    v_needs := true;
  end if;
  if not v_needs then return; end if;

  select id into v_tenant from public.ddrive_tenants where name = 'Migrated organisation' order by created_at limit 1;
  if v_tenant is null then
    insert into public.ddrive_tenants (name, kind, created_by) values ('Migrated organisation', 'other', null)
    returning id into v_tenant;
  end if;

  foreach t in array array['ddrive_hazards', 'ddrive_risks', 'ddrive_incidents', 'ddrive_undrr_scores',
                           'ddrive_scenarios', 'ddrive_plans', 'ddrive_messages', 'ddrive_documents'] loop
    execute format('update public.%I set tenant_id = $1 where tenant_id is null', t) using v_tenant;
  end loop;

  -- Everyone who already had an account becomes a viewer. An administrator promotes people afterwards.
  insert into public.ddrive_memberships (tenant_id, user_id, role, created_by)
  select v_tenant, u.id, 'viewer', null
  from public.ddrive_users u
  join auth.users a on a.id = u.id
  where not exists (select 1 from public.ddrive_memberships m where m.user_id = u.id)
  on conflict do nothing;

  update public.ddrive_users set active_tenant_id = v_tenant
  where active_tenant_id is null and exists (
    select 1 from public.ddrive_memberships m where m.user_id = ddrive_users.id and m.tenant_id = v_tenant);
end $$;

