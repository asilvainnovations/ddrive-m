-- ─── 5. Server stamping: organisation, author, time, version, id and reference ─
-- Trigger argument: the reference prefix ('R', 'P' …) or '' for tables without one.
create or replace function public.ddrive_touch()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_prefix text := coalesce(tg_argv[0], '');
begin
  if tg_op = 'INSERT' then
    if not public.ddrive_is_admin_context() then
      new.tenant_id := coalesce(new.tenant_id, public.ddrive_active_tenant());
      if new.tenant_id is null then
        raise exception 'Choose an organisation to work in before adding records.' using errcode = '42501';
      end if;
      new.created_by := auth.uid();
      new.created_at := now();
    else
      new.created_by := coalesce(new.created_by, auth.uid());
      new.created_at := coalesce(new.created_at, now());
    end if;
    new.updated_by := new.created_by;
    new.updated_at := new.created_at;
    new.version := 1;
    if v_prefix <> '' then
      -- The server issues the id and the reference number; values sent by the browser are ignored.
      new := jsonb_populate_record(new, jsonb_build_object(
        'id', gen_random_uuid()::text,
        'ref', public.ddrive_next_ref(new.tenant_id, v_prefix)));
    end if;
    return new;
  end if;

  -- UPDATE
  if not public.ddrive_is_admin_context() then
    if new.tenant_id is distinct from old.tenant_id
       or new.created_by is distinct from old.created_by
       or new.created_at is distinct from old.created_at
       or (to_jsonb(new) -> 'id') is distinct from (to_jsonb(old) -> 'id')
       or (to_jsonb(new) -> 'ref') is distinct from (to_jsonb(old) -> 'ref') then
      raise exception 'A record''s organisation, author, id and reference number cannot be changed.' using errcode = '42501';
    end if;
  end if;
  new.updated_by := auth.uid();
  new.updated_at := now();
  new.version := old.version + 1;
  return new;
end;
$$;

-- ─── 6. Risk score and level from the organisation's own thresholds ──────────
create or replace function public.ddrive_risk_level()
returns trigger
language plpgsql
security definer  -- reads the organisation's thresholds; changes nothing else
set search_path = public, pg_temp
as $$
declare
  th jsonb;
begin
  select risk_thresholds into th from public.ddrive_tenants where id = new.tenant_id;
  th := coalesce(th, '{"critical": 20, "high": 12, "medium": 6}'::jsonb);
  new.score := new.likelihood * new.impact;
  new.level := case
    when new.score >= (th ->> 'critical')::numeric then 'Critical'
    when new.score >= (th ->> 'high')::numeric then 'High'
    when new.score >= (th ->> 'medium')::numeric then 'Medium'
    else 'Low'
  end;
  return new;
end;
$$;

-- ─── 7. Plan approval and locks ──────────────────────────────────────────────
create or replace function public.ddrive_plan_guard()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
declare
  ignore_keys text[] := array['status', 'updated_at', 'updated_by', 'version', 'approved_by', 'approved_at', 'last_updated'];
begin
  if public.ddrive_is_admin_context() then
    return new;
  end if;

  if tg_op = 'INSERT' then
    -- New plans always start as drafts. Approval is a separate, recorded step.
    new.status := 'Draft';
    new.approved_by := null;
    new.approved_at := null;
    return new;
  end if;

  if old.status = 'Retired' then
    raise exception 'This plan is retired and cannot be changed.' using errcode = '42501';
  end if;

  if old.status = 'Approved' then
    if new.status <> 'Retired' or (to_jsonb(new) - ignore_keys) <> (to_jsonb(old) - ignore_keys) then
      raise exception 'Approved plans are locked. A DRRM officer can retire it; make a new draft to change it.'
        using errcode = '42501';
    end if;
    if not public.ddrive_has_role(old.tenant_id, 'drrm_officer') then
      raise exception 'Only a DRRM officer or administrator can retire a plan.' using errcode = '42501';
    end if;
    new.approved_by := old.approved_by;
    new.approved_at := old.approved_at;
    return new;
  end if;

  if new.status in ('Approved', 'Retired') and not public.ddrive_has_role(old.tenant_id, 'drrm_officer') then
    raise exception 'Only a DRRM officer or administrator can approve or retire a plan.' using errcode = '42501';
  end if;

  if new.status = 'Approved' then
    new.approved_by := auth.uid();
    new.approved_at := now();
  else
    new.approved_by := old.approved_by;
    new.approved_at := old.approved_at;
  end if;
  return new;
end;
$$;

-- ─── 8. Messages carry the sender's real name and role ───────────────────────
create or replace function public.ddrive_message_stamp()
returns trigger
language plpgsql
security definer  -- reads the sender's profile and membership
set search_path = public, pg_temp
as $$
begin
  if public.ddrive_is_admin_context() then
    return new;
  end if;
  new.user_id := auth.uid();
  new.user_name := coalesce((select nullif(full_name, '') from public.ddrive_users where id = auth.uid()),
                            (select email from public.ddrive_users where id = auth.uid()), 'Unknown user');
  new.role := coalesce(public.ddrive_my_role(new.tenant_id)::text, 'none');
  return new;
end;
$$;

-- ─── 9. Audit log ────────────────────────────────────────────────────────────
create or replace function public.ddrive_audit()
returns trigger
language plpgsql
security definer  -- writes to the audit log, which no user can write to directly
set search_path = public, pg_temp
as $$
declare
  o jsonb := case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) end;
  n jsonb := case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) end;
begin
  insert into public.ddrive_audit_log (tenant_id, table_name, record_id, action, actor, old_row, new_row)
  values (
    case when tg_table_name = 'ddrive_tenants' then coalesce((n ->> 'id')::uuid, (o ->> 'id')::uuid)
         else coalesce((n ->> 'tenant_id')::uuid, (o ->> 'tenant_id')::uuid) end,
    tg_table_name,
    coalesce(n ->> 'id', o ->> 'id', n ->> 'user_id', o ->> 'user_id'),
    tg_op,
    auth.uid(),
    o,
    n
  );
  return null;
end;
$$;

-- ─── 10. Attach the triggers (names sort so stamping runs first) ─────────────
do $$
declare
  r record;
  v_prefix text;
begin
  for r in
    select * from (values
      ('ddrive_hazards', ''), ('ddrive_risks', 'R'), ('ddrive_incidents', 'I'), ('ddrive_undrr_scores', ''),
      ('ddrive_scenarios', ''), ('ddrive_plans', 'P'), ('ddrive_messages', ''), ('ddrive_documents', 'D')
    ) as v(tbl, prefix)
  loop
    v_prefix := r.prefix;
    -- Only issue server ids where the id column holds text or a uuid.
    if v_prefix <> '' and (select data_type from information_schema.columns
                           where table_schema = 'public' and table_name = r.tbl and column_name = 'id')
                          not in ('text', 'uuid', 'character varying') then
      v_prefix := '';
    end if;
    execute format('drop trigger if exists ddrive_10_touch on public.%I', r.tbl);
    execute format('create trigger ddrive_10_touch before insert or update on public.%I
                    for each row execute function public.ddrive_touch(%L)', r.tbl, v_prefix);
    execute format('drop trigger if exists ddrive_90_audit on public.%I', r.tbl);
    execute format('create trigger ddrive_90_audit after insert or update or delete on public.%I
                    for each row execute function public.ddrive_audit()', r.tbl);
  end loop;
end $$;

