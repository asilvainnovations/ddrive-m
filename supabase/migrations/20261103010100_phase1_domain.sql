-- Recompute scores and levels for existing risks with the current thresholds.
update public.ddrive_risks r
set score = r.likelihood * r.impact,
    level = case
      when r.likelihood * r.impact >= coalesce((t.risk_thresholds ->> 'critical')::numeric, 20) then 'Critical'
      when r.likelihood * r.impact >= coalesce((t.risk_thresholds ->> 'high')::numeric, 12) then 'High'
      when r.likelihood * r.impact >= coalesce((t.risk_thresholds ->> 'medium')::numeric, 6) then 'Medium'
      else 'Low' end
from public.ddrive_tenants t
where t.id = r.tenant_id;
