-- DDRiVE-M Phase 2 · Official alerts (PAGASA CAP feed), watch areas, and linking alerts to hazard records.
-- See docs/adr/002-official-alert-ingestion.md. Safe to run more than once. Apply after the Phase 1 migrations.
--
-- Official alerts are public information from the issuing agency. They are stored once, shared by every
-- organisation, written only by the ingest service (service role), and never edited by users.

-- ─── 1. PSGC matching ────────────────────────────────────────────────────────
-- PAGASA uses 9-digit PSGC codes (RR PP MM BBB); PSA now issues 10-digit codes (RR PPP MM BBB).
-- The key is region + province, comparable across both forms. Metro Manila (region 13) has no provinces and
-- its 10-digit codes were reissued, so it matches at region level.
create or replace function public.ddrive_psgc_key(p_code text)
returns text
language sql
immutable
set search_path = public, pg_temp
as $$
  select case
    when c is null then null
    when left(c, 2) = '13' then '13'
    when length(c) = 9 then left(c, 2) || '0' || substr(c, 3, 2)
    when length(c) = 10 then left(c, 5)
    else null
  end
  from (select nullif(regexp_replace(coalesce(p_code, ''), '[^0-9]', '', 'g'), '') as c) s
$$;

create or replace function public.ddrive_norm_place(p_name text)
returns text
language sql
immutable
set search_path = public, pg_temp
as $$
  select nullif(lower(regexp_replace(btrim(coalesce(p_name, '')), '\s+', ' ', 'g')), '')
$$;

-- ─── 2. Official alerts ──────────────────────────────────────────────────────
create table if not exists public.ddrive_official_alerts (
  id uuid primary key default gen_random_uuid(),
  source text not null,                      -- issuing agency, e.g. 'PAGASA'
  identifier text not null,                  -- CAP <identifier>
  sender text,
  sent timestamptz not null,
  status text not null,                      -- CAP: Actual, Exercise, System, Test, Draft
  msg_type text not null,                    -- CAP: Alert, Update, Cancel, Ack, Error
  scope text,
  references_raw text,                       -- CAP <references>, verbatim
  event text not null,
  category text,
  urgency text,                              -- CAP fields are stored and shown verbatim
  severity text,
  certainty text,
  headline text,
  description text,
  instruction text,
  effective timestamptz,
  onset timestamptz,
  expires timestamptz,
  web text,
  signal_level int,                          -- PAGASA "Public Storm Warning Signal Level", when present
  region_label text,                         -- PAGASA region parameter
  area_names text[] not null default '{}',   -- CAP <areaDesc> values
  area_codes text[] not null default '{}',   -- CAP SAME geocodes (PSGC), verbatim
  area_keys text[] not null default '{}',    -- ddrive_psgc_key(area_codes)
  areas jsonb not null default '[]'::jsonb,  -- full areas incl. polygons, for maps
  cap_url text not null,
  license text,
  raw_xml text not null,                     -- the original CAP document, kept for provenance
  superseded_by uuid references public.ddrive_official_alerts (id) on delete set null,
  cancelled boolean not null default false,
  fetched_at timestamptz not null default now(),
  unique (source, identifier)
);
create index if not exists ddrive_official_alerts_sent_idx on public.ddrive_official_alerts (sent desc);
create index if not exists ddrive_official_alerts_keys_idx on public.ddrive_official_alerts using gin (area_keys);

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'ddrive_official_alerts_signal') then
    alter table public.ddrive_official_alerts add constraint ddrive_official_alerts_signal
      check (signal_level is null or signal_level between 1 and 5);
  end if;
end $$;

-- Record of every feed check, so the app can say how fresh its information is.
create table if not exists public.ddrive_ingest_runs (
  id bigint generated by default as identity primary key,
  source text not null,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  ok boolean,
  entries_seen int not null default 0,
  alerts_new int not null default 0,
  error text
);
create index if not exists ddrive_ingest_runs_source_idx on public.ddrive_ingest_runs (source, started_at desc);

-- ─── 3. Applying an alert from the feed (service role only) ──────────────────
-- Takes one parsed CAP alert as JSON. Inserts it once; when it updates or cancels earlier alerts
-- (CAP <references>: "sender,identifier,sent ..."), marks those as replaced or cancelled.
create or replace function public.ddrive_apply_official_alert(p jsonb)
returns text
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_id uuid;
  v_ref text;
  v_ref_identifier text;
  v_codes text[] := coalesce(array(select jsonb_array_elements_text(p -> 'area_codes')), '{}');
begin
  if not public.ddrive_is_admin_context() then
    raise exception 'Only the ingest service can record official alerts.' using errcode = '42501';
  end if;

  insert into public.ddrive_official_alerts (
    source, identifier, sender, sent, status, msg_type, scope, references_raw, event, category,
    urgency, severity, certainty, headline, description, instruction, effective, onset, expires, web,
    signal_level, region_label, area_names, area_codes, area_keys, areas, cap_url, license, raw_xml)
  values (
    p ->> 'source', p ->> 'identifier', p ->> 'sender', (p ->> 'sent')::timestamptz, p ->> 'status',
    p ->> 'msg_type', p ->> 'scope', p ->> 'references', p ->> 'event', p ->> 'category',
    p ->> 'urgency', p ->> 'severity', p ->> 'certainty', p ->> 'headline', p ->> 'description',
    p ->> 'instruction', (p ->> 'effective')::timestamptz, (p ->> 'onset')::timestamptz,
    (p ->> 'expires')::timestamptz, p ->> 'web', (p ->> 'signal_level')::int, p ->> 'region_label',
    coalesce(array(select jsonb_array_elements_text(p -> 'area_names')), '{}'),
    v_codes,
    coalesce(array(select distinct public.ddrive_psgc_key(c) from unnest(v_codes) c where public.ddrive_psgc_key(c) is not null), '{}'),
    coalesce(p -> 'areas', '[]'::jsonb), p ->> 'cap_url', p ->> 'license', p ->> 'raw_xml')
  on conflict (source, identifier) do nothing
  returning id into v_id;

  if v_id is null then
    return 'exists';
  end if;

  -- Each reference is "sender,identifier,sent", separated by spaces.
  foreach v_ref in array coalesce(string_to_array(btrim(coalesce(p ->> 'references', '')), ' '), '{}') loop
    v_ref_identifier := split_part(v_ref, ',', 2);
    continue when v_ref_identifier = '';
    if p ->> 'msg_type' = 'Cancel' then
      update public.ddrive_official_alerts set cancelled = true
      where source = p ->> 'source' and identifier = v_ref_identifier;
    else
      update public.ddrive_official_alerts set superseded_by = v_id
      where source = p ->> 'source' and identifier = v_ref_identifier and superseded_by is null;
    end if;
  end loop;

  -- A later-arriving alert may be referenced by one already stored.
  if exists (select 1 from public.ddrive_official_alerts o
             where o.source = p ->> 'source' and o.id <> v_id
               and o.references_raw like '%,' || (p ->> 'identifier') || ',%') then
    update public.ddrive_official_alerts set superseded_by = (
      select o.id from public.ddrive_official_alerts o
      where o.source = p ->> 'source' and o.id <> v_id and o.references_raw like '%,' || (p ->> 'identifier') || ',%'
      order by o.sent desc limit 1)
    where id = v_id;
  end if;

  return 'new';
end;
$$;

create or replace function public.ddrive_record_ingest_run(
  p_source text, p_started timestamptz, p_ok boolean, p_seen int, p_new int, p_error text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if not public.ddrive_is_admin_context() then
    raise exception 'Only the ingest service can record feed checks.' using errcode = '42501';
  end if;
  insert into public.ddrive_ingest_runs (source, started_at, finished_at, ok, entries_seen, alerts_new, error)
  values (p_source, p_started, now(), p_ok, p_seen, p_new, left(p_error, 2000));
  -- Keep 30 days of history.
  delete from public.ddrive_ingest_runs where started_at < now() - interval '30 days';
end;
$$;

-- ─── 4. Watch areas: the provinces an organisation follows ──────────────────
create table if not exists public.ddrive_watch_areas (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.ddrive_tenants (id) on delete cascade,
  label text not null,          -- province name as PAGASA writes it, e.g. 'Leyte'
  psgc_code text,               -- optional; 9- or 10-digit PSGC
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now()
);
create unique index if not exists ddrive_watch_areas_uidx
  on public.ddrive_watch_areas (tenant_id, public.ddrive_norm_place(label));

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'ddrive_watch_areas_label') then
    alter table public.ddrive_watch_areas add constraint ddrive_watch_areas_label check (length(btrim(label)) between 2 and 120);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'ddrive_watch_areas_psgc') then
    alter table public.ddrive_watch_areas add constraint ddrive_watch_areas_psgc check (psgc_code is null or psgc_code ~ '^[0-9]{9,10}$');
  end if;
end $$;

create or replace function public.ddrive_watch_area_stamp()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if not public.ddrive_is_admin_context() then
    new.tenant_id := coalesce(new.tenant_id, public.ddrive_active_tenant());
    new.created_by := auth.uid();
    new.created_at := now();
  end if;
  return new;
end;
$$;
drop trigger if exists ddrive_10_touch on public.ddrive_watch_areas;
create trigger ddrive_10_touch before insert on public.ddrive_watch_areas
  for each row execute function public.ddrive_watch_area_stamp();
drop trigger if exists ddrive_90_audit on public.ddrive_watch_areas;
create trigger ddrive_90_audit after insert or delete on public.ddrive_watch_areas
  for each row execute function public.ddrive_audit();

-- True when an alert covers one of the organisation's watch areas (by code, or by name as a fallback).
create or replace function public.ddrive_alert_in_watch_area(p_alert_keys text[], p_alert_names text[], p_tenant uuid)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.ddrive_watch_areas w
    where w.tenant_id = p_tenant
      and ((w.psgc_code is not null and public.ddrive_psgc_key(w.psgc_code) = any (p_alert_keys))
           or public.ddrive_norm_place(w.label) = any (array(select public.ddrive_norm_place(n) from unnest(p_alert_names) n)))
  )
$$;

-- Alerts that are in force: actual, not cancelled or replaced by a later update, not expired.
-- An alert without an expiry counts as in force for 24 hours after it was sent.
drop view if exists public.ddrive_active_alerts;
create view public.ddrive_active_alerts
with (security_invoker = true)
as
select a.id, a.source, a.identifier, a.sender, a.sent, a.status, a.msg_type, a.event, a.category,
       a.urgency, a.severity, a.certainty, a.headline, a.description, a.instruction, a.effective, a.onset,
       a.expires, a.web, a.signal_level, a.region_label, a.area_names, a.area_codes, a.cap_url, a.license,
       public.ddrive_alert_in_watch_area(a.area_keys, a.area_names, public.ddrive_active_tenant()) as in_watch_area
from public.ddrive_official_alerts a
where a.status = 'Actual'
  and a.msg_type in ('Alert', 'Update')
  and not a.cancelled
  and a.superseded_by is null
  and coalesce(a.expires, a.sent + interval '24 hours') > now();

